"""Proposal-only external research; never patches JARVIS or executes candidates.

Monday scheduling is opt-in via run_weekly_if_due(); importing/constructing does
not start threads, register cron jobs or send messages. The host must call it.
MindStore is append-only: processing is a linked event, not an SQL UPDATE.
apply_proposal is a trusted Hermes/operator API, NOT an agent tool or approval
service. The SkillLoader's worker API must never expose this object.
"""

