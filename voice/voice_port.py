"""Adapter contract for a future full-duplex voice model (JARVIS voice port).

Sir's decision (2026-10-16): the cascaded pipeline in voice_live.py (energy VAD ->
local ASR -> timeline -> say) is parked. A full-duplex speech model will be plugged
in later. This module fixes the seam so that adapter is the only new code needed.

Two roles, kept apart on purpose:

* ``DuplexVoiceBackend`` - the vendor adapter. Owns microphone/speaker audio,
  turn-taking, barge-in and speech synthesis. Knows nothing about JARVIS internals.
* ``VoiceEventSink`` - the JARVIS side. Receives what was heard and said, and is
  the only path by which voice reaches the single timeline (source_channel=voice).

Two operating modes, chosen per adapter:

* ``BRAIN`` - the duplex model is only ears and mouth. Each final user transcript
  goes to the JARVIS timeline; JARVIS's reply text is handed back via ``speak``.
  Personality, memory, affect and values stay in JARVIS. Works with today's
  ``/api/timeline/chat``.
* ``NATIVE`` - the duplex model answers by itself for lowest latency. JARVIS must
  then feed it live ``instructions`` (state, not scripts) and record both sides.
  Recording a turn without a model call needs a timeline record endpoint that does
  not exist yet; ``NativeModeUnavailable`` marks that gap instead of faking it.

No wording for Sir lives here: instructions are produced at runtime by JARVIS.
"""

