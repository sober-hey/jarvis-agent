class VoiceMode(enum.Enum):
    BRAIN = "brain"
    NATIVE = "native"


class SpeakPriority(enum.Enum):
    REPLY = "reply"  # Answer to what Sir just said.
    PROACTIVE = "proactive"  # JARVIS opens the conversation (outreach); may wait for a gap.
    URGENT = "urgent"  # Safety/urgent: may cut in over Sir, per core value 3.


@dataclass(frozen=True)
class VoiceContext:
    """Runtime state handed to the backend. Generated by JARVIS, never a template."""

    instructions: str
    locale: str = "zh-CN"
    metadata: dict[str, str] = field(default_factory=lambda: {})

    def __post_init__(self) -> None:
        if not self.instructions.strip():
            raise ValueError("instructions must be generated, not empty")
        if len(self.instructions) > MAX_INSTRUCTIONS_CHARS:
            raise ValueError("instructions exceed voice context limit")


class VoiceEventSink(Protocol):
    """Implemented by JARVIS. Backends call these from any thread."""

    def on_user_transcript(self, text: str, *, final: bool) -> None: ...

    def on_assistant_transcript(self, text: str, *, final: bool) -> None: ...

    def on_interrupted(self) -> None: ...

    def on_audio_level(self, speaker: str, level: float) -> None: ...

    def on_error(self, message: str) -> None: ...


class DuplexVoiceBackend(Protocol):
    """Implemented by the future vendor adapter."""

    @property
    def mode(self) -> VoiceMode: ...

    def start(self, context: VoiceContext, sink: VoiceEventSink) -> None: ...

    def update_context(self, context: VoiceContext) -> None: ...

    def speak(self, text: str, priority: SpeakPriority = SpeakPriority.REPLY) -> None: ...

    def interrupt(self) -> None: ...

    def close(self) -> None: ...


class NativeModeUnavailable(RuntimeError):
    """NATIVE mode needs a timeline record-only endpoint, not built yet."""


class BrainVoiceSink:
    """JARVIS side for BRAIN mode: final transcript -> timeline -> backend.speak.

    ``reply`` is the timeline call (``voice_live.TimelineClient.reply`` today), which
    already tags the turn ``source_channel=voice`` and never retries uncertain outcomes.
    ``on_level`` can feed avatar_signals mouth movement. One turn at a time: a new final
    transcript while a reply is pending supersedes it, mirroring barge-in.
    """

    def __init__(
        self,
        backend: DuplexVoiceBackend,
        reply: Callable[[str], str],
        *,
        on_level: Callable[[str, float], None] | None = None,
        on_error: Callable[[str], None] | None = None,
    ) -> None:
        if backend.mode is not VoiceMode.BRAIN:
            raise NativeModeUnavailable("BrainVoiceSink only drives BRAIN-mode backends")
        self._backend = backend
        self._reply = reply
        self._on_level = on_level
        self._on_error = on_error
        self._lock = threading.Lock()
        self._generation = 0

    def on_user_transcript(self, text: str, *, final: bool) -> None:
        if not final or not text.strip():
            return
        with self._lock:
            self._generation += 1
            generation = self._generation
        threading.Thread(target=self._answer, args=(text, generation), daemon=True).start()

    def _answer(self, text: str, generation: int) -> None:
        try:
            answer = self._reply(text)
        except Exception as exc:  # noqa: BLE001 - reported, never spoken
            self.on_error(f"timeline reply failed ({type(exc).__name__})")
            return
        with self._lock:
            if generation != self._generation:
                return  # Sir spoke again; this answer is stale.
        self._backend.speak(answer, SpeakPriority.REPLY)

    def on_assistant_transcript(self, text: str, *, final: bool) -> None:
        return  # In BRAIN mode the timeline already holds JARVIS's reply text.

    def on_interrupted(self) -> None:
        with self._lock:
            self._generation += 1

    def on_audio_level(self, speaker: str, level: float) -> None:
        if self._on_level is not None:
            self._on_level(speaker, max(0.0, min(1.0, level)))

    def on_error(self, message: str) -> None:
        if self._on_error is not None:
            self._on_error(message)
